#!/usr/bin/env node
/**
 * Generates `src/effects/diagrams/viz-gallery/variants.generated.ts` — one
 * `meta.variants` entry per edododraw visualization template.
 *
 * Generated rather than hand-written for one reason: the catalogue lives
 * upstream. `edododraw/demos` exports a curated, runnable `.edd` demo per
 * template with real sample content, so a template added in a future edododraw
 * release appears here on the next version bump and nobody has to notice.
 *
 * One template is deliberately excluded — see `EXCLUDED` below. Excluding it
 * silently would look like a bug, so the count and the reason are emitted into
 * the generated file.
 *
 * Run: npm run viz:variants
 */
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {ROOT} from './lib/fs.mjs';

const {VIZ_DEMOS} = await import('edododraw/demos');

/**
 * Templates left out of the gallery, each for a reason that can be seen.
 *
 * Five templates draw edododraw's character figures, and all five used to be
 * excluded as "broken". That stopped being true: the v2 figure grammar (0.14)
 * and the 0.16 polish pass made them read at 1080p, and a frame-by-frame review
 * judged four of them includable — `personas`, `vision`, `hole` and `quote`
 * (whose `pose: none` works as documented).
 *
 * `tug-of-war` stays out: its whole idea is two teams pulling one rope, and the
 * figures' hands still do not reach the rope. That is a fix in the character
 * poses, not in this library.
 */
const EXCLUDED = new Set(['tug-of-war']);

const tagline = (d) => String(d.description).replace(/`/g, '').slice(0, 120);

const usable = VIZ_DEMOS.filter((d) => !EXCLUDED.has(d.type)).sort((a, b) =>
  a.category === b.category ? a.type.localeCompare(b.type) : a.category.localeCompare(b.category),
);

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
/** A template's `.edd` source, as a backtick literal. Sources contain quotes and newlines. */
const src = (s) => '`' + String(s).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

const rows = usable
  .map(
    (d) => `  {
    id: '${esc(d.type)}',
    name: '${esc(d.title)}',
    tagline: '${esc(tagline(d))}',
    props: {vizType: '${esc(d.type)}', vizCategory: '${esc(d.category)}', source: ${src(d.code)}},
  },`,
  )
  .join('\n');

const categories = [...new Set(usable.map((d) => d.category))];

const out = `// AUTO-GENERATED by scripts/build-viz-variants.mjs — do not edit.
// Run \`npm run viz:variants\` after upgrading edododraw.
//
// ${usable.length} of edododraw's ${VIZ_DEMOS.length} visualization templates, each with the curated
// runnable demo the package ships for it. Left out: ${[...EXCLUDED].join(', ')} — its two
// teams pull a rope the character figures' hands do not reach, which is a fix in
// edododraw's poses rather than in this library.
//
// Categories: ${categories.join(' · ')}
import type {EffectMeta} from '../../../types';

export const VIZ_VARIANTS: NonNullable<EffectMeta['variants']> = [
${rows}
];

export const VIZ_TEMPLATE_COUNT = ${usable.length};
export const VIZ_EXCLUDED = ${JSON.stringify([...EXCLUDED])} as const;
export const VIZ_CATEGORIES = ${JSON.stringify(categories)} as const;
`;

const dest = join(ROOT, 'src', 'effects', 'diagrams', 'viz-gallery', 'variants.generated.ts');
writeFileSync(dest, out);
console.log(
  `viz:variants: ${usable.length} templates across ${categories.length} categories ` +
    `(${VIZ_DEMOS.length - usable.length} excluded: ${[...EXCLUDED].join(', ')})`,
);
