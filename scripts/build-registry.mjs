#!/usr/bin/env node
/**
 * Scans src/effects/<category>/<id>/ and generates src/registry.generated.ts
 * with explicit imports, so the same registry works under Remotion's bundler
 * (no import.meta.glob) and under Vite.
 *
 * Run: npm run registry
 */
import {readdirSync, statSync, writeFileSync, existsSync} from 'node:fs';
import {join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const effectsDir = join(root, 'src', 'effects');

const dirs = (p) => readdirSync(p).filter((d) => statSync(join(p, d)).isDirectory());

const entries = [];
for (const category of dirs(effectsDir).sort()) {
  for (const id of dirs(join(effectsDir, category)).sort()) {
    const dir = join(effectsDir, category, id);
    const tsx = readdirSync(dir).filter((f) => f.endsWith('.tsx'));
    if (tsx.length !== 1) {
      throw new Error(`${category}/${id}: expected exactly one .tsx file, found ${tsx.length}`);
    }
    if (!existsSync(join(dir, 'meta.ts'))) throw new Error(`${category}/${id}: missing meta.ts`);
    if (!existsSync(join(dir, 'prompt.md'))) throw new Error(`${category}/${id}: missing prompt.md`);
    const componentName = tsx[0].replace(/\.tsx$/, '');
    entries.push({category, id, componentName, file: `${category}/${id}/${tsx[0]}`});
  }
}

const ident = (e) => e.componentName.replace(/[^A-Za-z0-9]/g, '');

const publicAssets = readdirSync(join(root, 'public'))
  .filter((f) => !f.startsWith('.'))
  .sort();

const out = `// AUTO-GENERATED by scripts/build-registry.mjs — do not edit.
// Run \`npm run registry\` after adding or removing an effect.
import type {EffectEntry} from './types';
${entries
  .map(
    (e) =>
      `import {${e.componentName} as C_${ident(e)}} from './effects/${e.category}/${e.id}/${e.componentName}';\n` +
      `import {meta as M_${ident(e)}} from './effects/${e.category}/${e.id}/meta';`,
  )
  .join('\n')}

export const effects: readonly EffectEntry[] = [
${entries
  .map(
    (e) =>
      `  {meta: M_${ident(e)}, Component: C_${ident(e)} as React.ComponentType, file: '${e.file}'},`,
  )
  .join('\n')}
];

export const effectById = (id: string) => effects.find((e) => e.meta.id === id);

/**
 * Everything in public/. staticFile() returns a ROOT-absolute path with no way
 * to prefix a base, so a gallery served from a subpath (GitHub Pages project
 * sites, for instance) has to remap these before the app mounts. See
 * src/gallery/main.tsx.
 */
export const publicAssets: readonly string[] = [
${publicAssets.map((f) => `  '${f}',`).join('\n')}
];
`;

writeFileSync(join(root, 'src', 'registry.generated.ts'), out);
console.log(`registry: ${entries.length} effects across ${new Set(entries.map((e) => e.category)).size} categories`);
