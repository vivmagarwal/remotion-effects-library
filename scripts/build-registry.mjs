#!/usr/bin/env node
/**
 * Scans src/effects/<category>/<id>/ and generates src/registry.generated.ts
 * with explicit imports, so the same registry works under Remotion's bundler
 * (no import.meta.glob) and under Vite.
 *
 * Also writes out/meta.json — every effect's parsed metadata — so no other
 * script has to re-parse TypeScript with a regex.
 *
 * Run: npm run registry
 */
import {writeFileSync, existsSync, mkdirSync} from 'node:fs';
import {join} from 'node:path';
import {ROOT, OUT_DIR, walkEffects, walkPublic} from './lib/fs.mjs';
import {readMeta} from './lib/meta.mjs';

const entries = walkEffects();
for (const e of entries) {
  if (!existsSync(e.metaPath)) throw new Error(`${e.category}/${e.id}: missing meta.ts`);
  if (!existsSync(e.promptPath)) throw new Error(`${e.category}/${e.id}: missing prompt.md`);
}

const ident = (e) => e.componentName.replace(/[^A-Za-z0-9]/g, '');

const publicAssets = walkPublic().sort();

const out = `// AUTO-GENERATED by scripts/build-registry.mjs — do not edit.
// Run \`npm run registry\` after adding or removing an effect.
import type {EffectEntry} from './types';
${entries
  .map(
    (e) =>
      `import {${e.componentName} as C_${ident(e)}} from './effects/${e.category}/${e.id}/${e.componentName}';\n` +
      `import {meta as M_${ident(e)}} from './effects/${e.category}/${e.id}/meta';`,
  )
  .join('\n')}

/** One entry per folder, before variant expansion. */
const base: readonly EffectEntry[] = [
${entries
  .map(
    (e) =>
      `  {meta: M_${ident(e)}, Component: C_${ident(e)} as React.ComponentType, file: '${e.file}'},`,
  )
  .join('\n')}
];

/**
 * Base entries plus one per \`meta.variants\` entry.
 *
 * Expansion happens here, at runtime, rather than in the codegen: the variant
 * list already lives in a typed \`meta.ts\` the compiler checks, and duplicating
 * it into generated source would give it a second place to be wrong. A variant
 * inherits everything from its parent except the four fields it may override,
 * and carries \`parentId\` so the gallery can group a family and the prompt can
 * point at one brief rather than eighty-three.
 */
export const effects: readonly EffectEntry[] = base.flatMap((e) =>
  e.meta.variants && e.meta.variants.length > 0
    ? [
        e,
        ...e.meta.variants.map(
          (v): EffectEntry => ({
            meta: {
              ...e.meta,
              id: \`\${e.meta.id}--\${v.id}\`,
              name: v.name,
              tagline: v.tagline ?? e.meta.tagline,
              checkFrame: v.checkFrame ?? e.meta.checkFrame,
              posterFrame: v.posterFrame ?? e.meta.posterFrame,
              // A variant is a leaf; leaving the list on it would recurse.
              variants: undefined,
            },
            Component: e.Component,
            file: e.file,
            parentId: e.meta.id,
            variantProps: v.props,
          }),
        ),
      ]
    : [e],
);

/** Entries that are variants of something else, by parent id. */
export const variantsOf = (id: string) => effects.filter((e) => e.parentId === id);

export const effectById = (id: string) => effects.find((e) => e.meta.id === id);

/**
 * Everything in public/. staticFile() returns a ROOT-absolute path with no way
 * to prefix a base, so a gallery served from a subpath (GitHub Pages project
 * sites, for instance) has to remap these before the app mounts. See
 * src/gallery/main.tsx.
 */
export const publicAssets: readonly string[] = [
${publicAssets.map((f) => `  '${f}',`).join('\n')}
];
`;

writeFileSync(join(ROOT, 'src', 'registry.generated.ts'), out);

// out/meta.json — the parsed metadata, so the gates never re-parse meta.ts.
mkdirSync(OUT_DIR, {recursive: true});
const metas = entries.map((e) => {
  const {keyLines, ...meta} = readMeta(e.metaPath);
  return {...meta, dir: e.category + '/' + e.id, folder: e.id, folderCategory: e.category, file: e.file, componentName: e.componentName};
});
writeFileSync(join(OUT_DIR, 'meta.json'), JSON.stringify(metas, null, 2) + '\n');

console.log(
  `registry: ${entries.length} effects across ${new Set(entries.map((e) => e.category)).size} categories` +
    ` (out/meta.json: ${metas.length}, publicAssets: ${publicAssets.length})`,
);
